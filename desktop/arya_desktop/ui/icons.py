from PySide6.QtGui import QIcon, QPixmap, QPainter
from PySide6.QtSvg import QSvgRenderer
from PySide6.QtCore import QByteArray, Qt

def create_svg_icon(svg_string: str, color: str = "#c9cbd1") -> QIcon:
    """Create a QIcon from an SVG string."""
    # Replace currentColor with our desired default color
    if color:
        svg_string = svg_string.replace('currentColor', color)
        
    svg_bytes = QByteArray(svg_string.encode('utf-8'))
    renderer = QSvgRenderer(svg_bytes)
    
    pixmap = QPixmap(24, 24)
    pixmap.fill(Qt.transparent)
    painter = QPainter(pixmap)
    renderer.render(painter)
    painter.end()
    
    icon = QIcon()
    icon.addPixmap(pixmap, QIcon.Normal, QIcon.Off)
    
    # Active/Hover state (white)
    if color:
        active_svg = svg_string.replace(color, "#ffffff")
        active_renderer = QSvgRenderer(QByteArray(active_svg.encode('utf-8')))
        active_pixmap = QPixmap(24, 24)
        active_pixmap.fill(Qt.transparent)
        active_painter = QPainter(active_pixmap)
        active_renderer.render(active_painter)
        active_painter.end()
        icon.addPixmap(active_pixmap, QIcon.Active, QIcon.On)
        icon.addPixmap(active_pixmap, QIcon.Selected, QIcon.On)
        icon.addPixmap(active_pixmap, QIcon.Normal, QIcon.On)

    return icon


